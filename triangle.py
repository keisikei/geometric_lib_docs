def area(a, h):
    '''

    Принимает:

    a (int or float): основание треугольника
    h (int or float): высота треугольника

    Возвращаемое значение:

    a * h / 2 (float): площадь треугольника

    '''
    return a * h / 2

def perimeter(a, b, c):
    '''

    Принимает:

    a (int or float): первая сторона
    b (int or float): вторая сторона
    c (int or float): третья сторона

    Возвращает:
       
    a + b + c (int or float): периметр треугольника

    '''
    return a + b + c
