def area(a, b):
    '''

    Принимает:
    
    a (int or float): длина первой стороны
    b (int or float): длина второй стороны

    Возвращает:

    a * b (int or float): площадь прямоугольника

    '''
    return a * b

def perimeter(a, b):
    '''

    Принимает:

    a (int or float): длина первой стороны
    b (int or float): длина второй стороны

    Возвращает:

    2 * (a + b) (int/float): периметр прямоугольника

    '''
    return 2 * (a + b)